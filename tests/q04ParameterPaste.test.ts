import {beforeEach,expect,it,vi} from 'vitest';
vi.mock('../src/engine/image/decoder',()=>({decodeImageFile:vi.fn(async(file:File)=>({workspaceKey:file.name,name:file.name,sourceUrl:'blob:'+file.name,originalWidth:64,originalHeight:48}))}));
vi.mock('../src/engine/image/thumbnails',()=>({clearThumbnails:vi.fn(),requestThumbnail:vi.fn()}));
import {useWorkspaceStore as ws} from '../src/stores/workspaceStore';
import {useEditorStore as editor} from '../src/stores/editorStore';
import {applyFilmToSelection,clearClipboard,copySelection,pasteToSelection} from '../src/poc/q04/integration/parameterPaste';
const entry=(name:string)=>({id:name,name,path:name,getFile:async()=>new File(['test'],name,{type:'image/png'})});
beforeEach(async()=>{clearClipboard();ws.getState().close();ws.getState().setEntries(['a','b','c'].map(entry),'Folder');await ws.getState().select('a');});
it('copies only the chosen groups to the clip and pastes them across the selection',async()=>{
 editor.getState().setAdjustment('exposure',1.2);
 editor.getState().setFilm('FS-006');
 const clip=copySelection(['tone']);
 expect(clip).toMatchObject({sourceId:'a',groups:['tone']});
 expect(clip?.film).toBeUndefined();
 ws.getState().clickThumbnail('b');
 await vi.waitFor(()=>expect(ws.getState().activeId).toBe('b'));
 editor.getState().setAdjustment('exposure',-0.5);
 ws.getState().toggleSelection('c');
 expect([...ws.getState().selection.ids].sort()).toEqual(['b','c']);
 const report=pasteToSelection();
 expect(report).toEqual({pasted:2,active:'b'});
 expect(editor.getState().adjustments.exposure).toBe(1.2);
 expect(editor.getState().activeFilmId).toBe('FS-001');
 editor.getState().undo();
 expect(editor.getState().adjustments.exposure).toBe(-0.5);
 ws.getState().clickThumbnail('c');
 await vi.waitFor(()=>expect(ws.getState().activeId).toBe('c'));
 expect(editor.getState().adjustments.exposure).toBe(1.2);
});
it('applies a recommended film to every selected photo as one undo step',async()=>{
 ws.getState().toggleSelection('b');
 expect([...ws.getState().selection.ids].sort()).toEqual(['a','b']);
 const report=applyFilmToSelection('FS-003');
 expect(report).toEqual({pasted:2,active:'a'});
 expect(editor.getState().activeFilmId).toBe('FS-003');
 editor.getState().undo();
 expect(editor.getState().activeFilmId).toBe('FS-001');
 ws.getState().clickThumbnail('b');
 await vi.waitFor(()=>expect(ws.getState().activeId).toBe('b'));
 expect(editor.getState().activeFilmId).toBe('FS-003');
});

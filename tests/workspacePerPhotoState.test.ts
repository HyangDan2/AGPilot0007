import {beforeEach,expect,it,vi} from 'vitest';
vi.mock('../src/engine/image/decoder',()=>({decodeImageFile:vi.fn(async(file:File)=>({workspaceKey:file.name,name:file.name,sourceUrl:'blob:'+file.name,originalWidth:64,originalHeight:48}))}));
vi.mock('../src/engine/image/thumbnails',()=>({clearThumbnails:vi.fn(),requestThumbnail:vi.fn()}));
import {useWorkspaceStore as ws} from '../src/stores/workspaceStore';
import {useEditorStore as editor} from '../src/stores/editorStore';
import {DEFAULT_ADJUSTMENTS} from '../src/types/film';
import {defaultCurves} from '../src/types/curves';
import {normalizeCamera} from '../src/types/camera';
import {defaultColorMixer} from '../src/types/colorMixer';
import {DEFAULT_SHARPENING} from '../src/types/sharpening';
const entry=(name:string)=>({id:name,name,path:name,getFile:async()=>new File(['test'],name,{type:'image/png'})});
const baseline=()=>({image:null,adjustments:{...DEFAULT_ADJUSTMENTS},activeFilmId:'FS-001' as const,activePresetId:null,curves:defaultCurves(),camera:normalizeCamera(),colorMixer:defaultColorMixer(),sharpening:{...DEFAULT_SHARPENING},historyIndex:0,canUndo:false,canRedo:false});
beforeEach(()=>{ws.getState().close();editor.setState(baseline());ws.getState().setEntries([entry('a'),entry('b')],'Folder');});
it('opens an unvisited photo from the default EditState instead of inheriting the previous edit',async()=>{
 editor.setState({adjustments:{...DEFAULT_ADJUSTMENTS,exposure:1.2},activeFilmId:'FS-006',activePresetId:'portra-400'});
 await ws.getState().select('a');
 const state=editor.getState();
 expect(state.image?.workspaceKey).toBe('a');
 expect(state.adjustments).toEqual(DEFAULT_ADJUSTMENTS);
 expect(state.activeFilmId).toBe('FS-001');
 expect(state.activePresetId).toBeNull();
 expect(state.curves).toEqual(defaultCurves());
 expect(state.camera).toEqual(normalizeCamera());
 expect(state.colorMixer).toEqual(defaultColorMixer());
 expect(state.sharpening).toEqual(DEFAULT_SHARPENING);
});
it('restores the saved session of a visited photo and keeps unvisited photos at defaults',async()=>{
 await ws.getState().select('a');
 editor.setState({adjustments:{...editor.getState().adjustments,exposure:1.2},activeFilmId:'FS-006'}); 
 await ws.getState().select('b');
 expect(editor.getState().image?.workspaceKey).toBe('b');
 expect(editor.getState().adjustments.exposure).toBe(0);
 expect(editor.getState().activeFilmId).toBe('FS-001');
 await ws.getState().select('a');
 expect(editor.getState().image?.workspaceKey).toBe('a');
 expect(editor.getState().adjustments.exposure).toBe(1.2);
 expect(editor.getState().activeFilmId).toBe('FS-006');
});
it('does not reset anything when the already-open photo is selected again',async()=>{
 await ws.getState().select('a');
 editor.setState({adjustments:{...editor.getState().adjustments,exposure:-0.4},activeFilmId:'FS-010',sharpening:{...DEFAULT_SHARPENING,amount:55}});
 const before=editor.getState();
 await ws.getState().select('a');
 const after=editor.getState();
 expect(after.image?.workspaceKey).toBe('a');
 expect(after.adjustments.exposure).toBe(-0.4);
 expect(after.activeFilmId).toBe('FS-010');
 expect(after.sharpening.amount).toBe(55);
 expect(after.history.length).toBe(before.history.length);
 expect(after.historyIndex).toBe(before.historyIndex);
 expect(after.canUndo).toBe(before.canUndo);
});
